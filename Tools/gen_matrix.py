"""Generates the weapon x modifier compatibility matrix (modifiers.md R-MOD-02, gate step 'matrix').

Usage:  python -I Tools/gen_matrix.py          write Docs/09_Catalog/matrix.csv
        python -I Tools/gen_matrix.py --check  exit 1 if matrix.csv was hand-edited or is out of date
The rule is R-MOD-01 over weapons.csv, modifiers.csv and flag_compat.csv: at least one required cap, no blocked cap, and a
carried flag resolves native on the weapon's caps walked in order. T-MOD-02 checks every cell against DTModCompat::IsCompatible.
Never hand-edited, never union-merged: on a conflict, regenerate.
"""

import csv
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOG = os.path.join(ROOT, "Docs", "09_Catalog")
OUT = os.path.join(CATALOG, "matrix.csv")
HEADER = "# GENERATED by Tools/gen_matrix.py from weapons.csv, modifiers.csv, flag_compat.csv. Do not edit: regenerate."


def rows(name, catalog=CATALOG):
	with open(os.path.join(catalog, name), encoding="utf-8", newline="") as f:
		return list(csv.DictReader(f))


def caps_of(cell):
	return [c for c in cell.split(";") if c]


def resolves_native(flag_row, weapon_caps):
	"""The walk of R-WPN-08: the first cap whose cell is not `none` decides."""
	for cap in weapon_caps:
		cell = flag_row[cap]
		if cell != "none":
			return cell == "native"
	return False


def compatible(weapon_caps, mod, flags):
	required = caps_of(mod["required_caps"])
	if required and not set(required) & set(weapon_caps):
		return False
	if set(caps_of(mod["blocked_caps"])) & set(weapon_caps):
		return False
	if mod["flag"]:
		return resolves_native(flags[mod["flag"]], weapon_caps)
	return True


def render(catalog=CATALOG):
	weapons = {}
	for row in rows("weapons.csv", catalog):
		weapons.setdefault(row["id"], caps_of(row["caps"]))
	flags = {row["flag"]: row for row in rows("flag_compat.csv", catalog)}
	out = io.StringIO()
	w = csv.writer(out, lineterminator="\n")
	out.write(HEADER + "\n")
	w.writerow(["modifier"] + list(weapons))
	for mod in rows("modifiers.csv", catalog):
		w.writerow([mod["id"]] + ["yes" if compatible(c, mod, flags) else "no" for c in weapons.values()])
	return out.getvalue()


def main(argv):
	text = render()
	if "--check" in argv:
		have = None
		if os.path.exists(OUT):
			with open(OUT, encoding="utf-8", newline="") as f:
				have = f.read()
		if have != text:
			print("MATRIX: FAIL (matrix.csv is hand-edited or out of date; run python -I Tools/gen_matrix.py)")
			return 1
		print(f"MATRIX: PASS ({text.count(chr(10)) - 2} modifiers)")
		return 0
	with open(OUT, "w", encoding="utf-8", newline="") as f:
		f.write(text)
	print(f"wrote {os.path.relpath(OUT, ROOT)}")
	return 0


if __name__ == "__main__":
	sys.exit(main(sys.argv[1:]))
