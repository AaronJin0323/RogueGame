"""Generates the text of Source/Dusktracer/Audio/DTSoundsGen.h from Docs/09_Catalog/sounds.csv (02_Systems/audio.md Data;
D-056 item 1). Stdlib only.

Usage:  python -I Tools/audio/gen_sounds.py --check   exit 1 if the header is missing or out of date
        python -I Tools/audio/gen_sounds.py --write   write the header (the runtime job does, with its first C++)
        [--csv <sounds.csv>] [--out <header>]        another catalog or header (the tests)

The header holds namespace DTCat: an enum of sound ids, the enums of a row's cells and one constexpr row per sound
with what the runtime reads (side, class, variants, loop, volume, pitch rule, interval, voices, aggregation gain,
grid, asset path). Length, loudness, zone, recipe and confusion set are the gate's and stay out. With no rows the
table holds one empty entry and SoundCount is 0, since C++ has no array of length zero.
A catalog that does not validate (audio_build.validate) writes nothing.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import audio_build as B  # noqa: E402

HEADER = os.path.join(B.ROOT, "Source", "Dusktracer", "Audio", "DTSoundsGen.h")
ASSET_ROOT = "/Game/DT/Audio/SFX/"
ENUMS = (("ESoundSide", "side", {"player": "Player", "danger": "Danger", "ui": "UI"}),
	("ESoundClass", "class", {"Player": "Player", "Danger": "Danger", "UI": "UI", "Music": "Music"}),
	("ESoundPitch", "pitch", {"fixed": "Fixed", "key": "Key", "ladder": "Ladder"}))


def _float(text):
	value = repr(float(text))
	return (value if ("e" in value or "." in value) else value + ".0") + "f"


def symbol(row):
	return row["id"].replace(".", "_")


def render(rows):
	"""The header text for valid catalog rows, in catalog order."""
	lines = [
		"// GENERATED by Tools/audio/gen_sounds.py from Docs/09_Catalog/sounds.csv. Do not edit: change the CSV and regenerate.",
		"#pragma once",
		"",
		"#include \"CoreMinimal.h\"",
		"",
		"namespace DTCat",
		"{",
	]
	for name, _, values in ENUMS:
		lines.append(f"\tenum class {name} : uint8 {{ {', '.join(values.values())} }};")
	lines.append("")
	lines.append("\t/** One id per sounds.csv row, in its order; Count is the number of rows. */")
	lines.append("\tenum class ESoundId : uint16")
	lines.append("\t{")
	for row in rows:
		lines.append(f"\t\t{symbol(row)},")
	lines.append("\t\tCount")
	lines.append("\t};")
	lines += [
		"",
		"\tstruct FSoundRow",
		"\t{",
		"\t\tconst TCHAR* Id;",
		"\t\tconst TCHAR* Asset;      // variant 0; variant n > 0 is Asset + \"_n\"",
		"\t\tESoundSide Side;",
		"\t\tESoundClass Class;",
		"\t\tint32 Variants;",
		"\t\tbool bLoop;",
		"\t\tfloat Volume;",
		"\t\tESoundPitch Pitch;",
		"\t\tint32 IntervalMs;",
		"\t\tint32 Voices;",
		"\t\tfloat AggGain;",
		"\t\tbool bGrid;",
		"\t};",
		"",
		f"\tinline constexpr int32 SoundCount = {len(rows)};",
	]
	if rows:
		lines.append("\tinline constexpr FSoundRow Sounds[SoundCount] =")
		lines.append("\t{")
		for row in rows:
			side = ENUMS[0][2][row["side"]]
			klass = ENUMS[1][2][row["class"]]
			pitch = ENUMS[2][2][row["pitch"]]
			lines.append(f"\t\t{{ TEXT(\"{row['id']}\"), TEXT(\"{ASSET_ROOT}{B.base_name(row)}\"), ESoundSide::{side}, ESoundClass::{klass}, "
				f"{int(row['variants'])}, {'true' if row['loop'] == '1' else 'false'}, {_float(row['volume'])}, ESoundPitch::{pitch}, "
				f"{int(row['interval_ms'])}, {int(row['voices'])}, {_float(row['agg_gain'])}, {'true' if row['grid'] == '1' else 'false'} }},")
		lines.append("\t};")
	else:
		lines.append("\tinline constexpr FSoundRow Sounds[1] = { {} }; // no rows yet: one empty entry, never read while SoundCount is 0")
	lines += ["}", ""]
	return "\r\n".join(lines)


def _arg(argv, flag, default):
	return argv[argv.index(flag) + 1] if flag in argv and argv.index(flag) + 1 < len(argv) else default


def main(argv):
	csv_path = _arg(argv, "--csv", B.CATALOG)
	out = _arg(argv, "--out", HEADER)
	rows, errors = B.read_catalog(csv_path)
	errors += B.validate(rows, _arg(argv, "--recipes", B.RECIPES))
	if errors:
		for e in errors:
			print(f"error: {e}")
		print(f"SOUNDS: FAIL ({len(errors)} catalog error(s); nothing written)")
		return 1
	text = render(rows)
	current = None
	if os.path.exists(out):
		with open(out, encoding="utf-8", newline="") as f:
			current = f.read()
	if "--write" in argv:
		if current != text:
			os.makedirs(os.path.dirname(out), exist_ok=True)
			with open(out, "w", encoding="utf-8", newline="") as f:
				f.write(text)
			print(f"wrote {out}")
		print(f"SOUNDS: PASS ({len(rows)} row(s))")
		return 0
	if current is None:
		print(f"SOUNDS: FAIL ({os.path.basename(out)} does not exist; python -I Tools/audio/gen_sounds.py --write)")
		return 1
	if current != text:
		print(f"SOUNDS: FAIL ({os.path.basename(out)} out of date; python -I Tools/audio/gen_sounds.py --write)")
		return 1
	print(f"SOUNDS: PASS ({len(rows)} row(s))")
	return 0


if __name__ == "__main__":
	if not any(flag in sys.argv for flag in ("--check", "--write")):
		print(__doc__)
		sys.exit(2)
	sys.exit(main(sys.argv[1:]))
