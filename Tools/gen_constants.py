"""Generates Source/Dusktracer/Core/DTConstantsGen.h from Docs/constants.yaml (R-TEC-07, T-TEC-07) and
Source/Dusktracer/Core/DTPaletteGen.h from the token table of Docs/04_Presentation.md §3 (R-PRE-09, T-PRE-09).

Usage:  python -I Tools/gen_constants.py          write the header
        python -I Tools/gen_constants.py --check  exit 1 if the header is out of date (gate step 'constants')
Numbers become constexpr values in namespace DTConst (SIM.FIXED_HZ -> DTConst::SIM_FIXED_HZ); a two-number list
becomes <KEY>_MIN and <KEY>_MAX; strings and null (GATED, not yet measured) become comments only.
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dtconst  # noqa: E402

HEADER = os.path.join(dtconst.ROOT, "Source", "Dusktracer", "Core", "DTConstantsGen.h")


def _num(v):
	if isinstance(v, bool) or not isinstance(v, (int, float)):
		return None
	if isinstance(v, int):
		return "int32", str(v)
	text = repr(float(v))
	return "float", (text if ("e" in text or "." in text) else text + ".0") + "f"


def render(constants):
	lines = [
		"// GENERATED by Tools/gen_constants.py from Docs/constants.yaml. Do not edit: change the YAML and regenerate.",
		"#pragma once",
		"",
		"#include \"CoreMinimal.h\"",
		"",
		"namespace DTConst",
		"{",
	]
	section = None
	for key, c in constants.items():
		if c["section"] != section:
			section = c["section"]
			lines.append(f"\t// {section}")
		name = key.replace(".", "_")
		note = f"{c['unit']}, {c['tag']}"
		v = c["value"]
		if isinstance(v, list) and len(v) == 2 and all(_num(x) for x in v):
			for suffix, x in (("MIN", v[0]), ("MAX", v[1])):
				t, s = _num(x)
				lines.append(f"\tinline constexpr {t} {name}_{suffix} = {s}; // {note}")
		elif _num(v):
			t, s = _num(v)
			lines.append(f"\tinline constexpr {t} {name} = {s}; // {note}")
		else:
			lines.append(f"\t// {name} = {v!r} ({note}) - not a number; no constant generated")
	lines += ["}", ""]
	return "\r\n".join(lines)


PALETTE_DOC = os.path.join(dtconst.ROOT, "Docs", "04_Presentation.md")
PALETTE_HEADER = os.path.join(dtconst.ROOT, "Source", "Dusktracer", "Core", "DTPaletteGen.h")
_TOKEN_ROW = re.compile(r"^\|\s*`Pal\.([A-Za-z]+(?:\.[A-Za-z]+)+)`\s*\|\s*#([0-9A-Fa-f]{6})\s*\|")
# Colour literals that bypass the palette (T-PRE-09): FromHex calls and 6-digit hex strings.
_COLOUR_LITERAL = re.compile(r"FromHex\s*\(|TEXT\(\s*\"#?[0-9A-Fa-f]{6}\"\s*\)|\"#[0-9A-Fa-f]{6}\"")


def load_palette():
	"""Reads the token table of 04_Presentation §3: {'Player.Core': 'EEF7FF', ...} in document order."""
	tokens = {}
	with open(PALETTE_DOC, encoding="utf-8") as f:
		for line in f:
			m = _TOKEN_ROW.match(line)
			if m:
				tokens[m.group(1)] = m.group(2).upper()
	return tokens


def render_palette(tokens):
	lines = [
		"// GENERATED by Tools/gen_constants.py from Docs/04_Presentation.md §3 (palette tokens, R-PRE-09). Do not edit.",
		"#pragma once",
		"",
		"#include \"CoreMinimal.h\"",
		"",
		"namespace DTPal",
		"{",
	]
	for name, hexv in tokens.items():
		r, g, b = (int(hexv[i:i + 2], 16) for i in (0, 2, 4))
		lines.append(f"\tinline constexpr FColor {name.replace('.', '_')} = FColor({r}, {g}, {b}); // #{hexv}")
	lines += ["", "\t/** Linear colour of a token, for materials and per-instance custom data. */",
			  "\tinline FLinearColor Linear(const FColor& Token) { return FLinearColor(Token); }", "}", ""]
	return "\r\n".join(lines)


def colour_literals():
	"""Source files that spell a colour outside the generated headers."""
	hits = []
	for base, _, files in os.walk(os.path.join(dtconst.ROOT, "Source")):
		for name in files:
			if not name.endswith((".h", ".cpp")) or name.endswith("Gen.h"):
				continue
			path = os.path.join(base, name)
			with open(path, encoding="utf-8", errors="replace") as f:
				for n, line in enumerate(f, 1):
					if _COLOUR_LITERAL.search(line):
						hits.append(f"{os.path.relpath(path, dtconst.ROOT)}:{n}")
	return hits


def _read(path):
	if os.path.exists(path):
		with open(path, encoding="utf-8", newline="") as f:
			return f.read()
	return None


def main(argv):
	outputs = [(HEADER, render(dtconst.load())), (PALETTE_HEADER, render_palette(load_palette()))]
	if "--check" in argv:
		stale = [os.path.basename(p) for p, text in outputs if _read(p) != text]
		literals = colour_literals()
		for hit in literals:
			print(f"error: colour literal outside the palette (T-PRE-09): {hit}")
		if stale:
			print(f"CONSTANTS: FAIL ({', '.join(stale)} out of date; run python -I Tools/gen_constants.py)")
			return 1
		if literals:
			print(f"CONSTANTS: FAIL ({len(literals)} colour literal(s); use DTPal:: tokens)")
			return 1
		print("CONSTANTS: PASS (constants + palette)")
		return 0
	for path, text in outputs:
		os.makedirs(os.path.dirname(path), exist_ok=True)
		if _read(path) != text:
			with open(path, "w", encoding="utf-8", newline="") as f:
				f.write(text)
			print(f"wrote {os.path.relpath(path, dtconst.ROOT)}")
	return 0


if __name__ == "__main__":
	sys.exit(main(sys.argv[1:]))
