"""Generates Source/Dusktracer/Core/DTConstantsGen.h from Docs/constants.yaml (R-TEC-07, T-TEC-07).

Usage:  python -I Tools/gen_constants.py          write the header
        python -I Tools/gen_constants.py --check  exit 1 if the header is out of date (gate step 'constants')
Numbers become constexpr values in namespace DTConst (SIM.FIXED_HZ -> DTConst::SIM_FIXED_HZ); a two-number list
becomes <KEY>_MIN and <KEY>_MAX; strings and null (GATED, not yet measured) become comments only.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dtconst  # noqa: E402

HEADER = os.path.join(dtconst.ROOT, "Source", "Dusktracer", "Core", "DTConstantsGen.h")


def _num(v):
	if isinstance(v, bool) or not isinstance(v, (int, float)):
		return None
	if isinstance(v, int):
		return "int32", str(v)
	text = repr(float(v))
	return "float", (text if ("e" in text or "." in text) else text + ".0") + "f"


def render(constants):
	lines = [
		"// GENERATED by Tools/gen_constants.py from Docs/constants.yaml. Do not edit: change the YAML and regenerate.",
		"#pragma once",
		"",
		"#include \"CoreMinimal.h\"",
		"",
		"namespace DTConst",
		"{",
	]
	section = None
	for key, c in constants.items():
		if c["section"] != section:
			section = c["section"]
			lines.append(f"\t// {section}")
		name = key.replace(".", "_")
		note = f"{c['unit']}, {c['tag']}"
		v = c["value"]
		if isinstance(v, list) and len(v) == 2 and all(_num(x) for x in v):
			for suffix, x in (("MIN", v[0]), ("MAX", v[1])):
				t, s = _num(x)
				lines.append(f"\tinline constexpr {t} {name}_{suffix} = {s}; // {note}")
		elif _num(v):
			t, s = _num(v)
			lines.append(f"\tinline constexpr {t} {name} = {s}; // {note}")
		else:
			lines.append(f"\t// {name} = {v!r} ({note}) - not a number; no constant generated")
	lines += ["}", ""]
	return "\r\n".join(lines)


def main(argv):
	text = render(dtconst.load())
	existing = None
	if os.path.exists(HEADER):
		with open(HEADER, encoding="utf-8", newline="") as f:
			existing = f.read()
	if "--check" in argv:
		if existing != text:
			print("CONSTANTS: FAIL (DTConstantsGen.h is out of date; run python -I Tools/gen_constants.py)")
			return 1
		print("CONSTANTS: PASS")
		return 0
	os.makedirs(os.path.dirname(HEADER), exist_ok=True)
	if existing != text:
		with open(HEADER, "w", encoding="utf-8", newline="") as f:
			f.write(text)
		print(f"wrote {os.path.relpath(HEADER, dtconst.ROOT)}")
	else:
		print("up to date")
	return 0


if __name__ == "__main__":
	sys.exit(main(sys.argv[1:]))
