"""Elite anchors (02_Systems/enemy_art.md R-EAR-08, D-076): where an elite's parts sit on its role's hull, read from the hull generators.

    python -I Tools/elite_anchors.py           writes Source/Dusktracer/Enemies/DTEliteAnchorsGen.h
    python -I Tools/elite_anchors.py --check   exit 1 if that header is hand-edited or out of date with the generators

The anchors are measured on the lists Tools/blender/enemy_<role>.py states (through Tools/enemy_shapes.py, as Blender builds them), so
the table, the generators and the committed meshes are one thing; never typed by hand. Every length is in drawn radii (the elite's hit
radius times C.ELITE.DRAW_SCALE), in the hull's own frame as the game draws it: +X the facing, +Z up from the floor, Y as Unreal's.

place() is the placement DTElite::BuildParts makes from them, in plain Python, for Tools/enemy_art_check.py's `elite parts` reading; a
tools test holds the C++ layout numbers equal to LAYOUT below. cube_place() is today's placement from the hit circle (the grey box and the
boss keep it, R-EAR-06), the "before" the reading must fail on the role hulls.
"""

import importlib.util
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dtconst  # noqa: E402
import enemy_shapes as es  # noqa: E402

TOOLS = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TOOLS)
OUT = os.path.join(ROOT, "Source", "Dusktracer", "Enemies", "DTEliteAnchorsGen.h")
ROLES = ("Swarm", "Tank", "Rusher", "Turret")  # EDTEnemyRole order; the boss has no mesh and keeps the cube
AFFIXES = ("Armored", "Swift", "Volatile", "Splitter", "Vampiric", "Shielded")  # the affix parts of elites.md R-ELT-11
HEADER = "// GENERATED by Tools/elite_anchors.py from Tools/blender/enemy_<role>.py (02_Systems/enemy_art.md R-EAR-08). Do not edit: regenerate."

# Layout in multiples of the part size P (C.ELITE.PART_RATIO x the drawn radius), as DTElite.cpp's DTEliteLocal states it; a tools test
# reads the same literals there. The first six are today's (elites.md R-ELT-11); LightCover is the mend's: the light is the optic's own
# bounds this much over, so it covers the optic it takes the place of.
LAYOUT = {"VaneYawDeg": 30.0, "VaneLength": 2.5, "ThinPart": 0.5, "ReactorSize": 1.5, "SpikeLength": 2.5, "ShieldOrbit": 2.0, "LightCover": 1.15}
SIDE_LONG_RATIO = 0.4  # a side plate rests on the widest part at least this share of the hull's length
SIDE_FLAT_RATIO = 0.5  # whose greatest half-width holds along at least this share of the part's own length
FACE_EPS = 1e-6

FIELDS = (
	("Front", "the hull's reach in front of the hit centre"),
	("Rear", "its reach behind the hit centre"),
	("HalfWidth", "its greatest half-width"),
	("Bottom", "its lowest point above the floor"),
	("Top", "its highest point"),
	("Reach", "its longest reach from the hit centre, seen from above"),
	("OpticX", "the optic's centre in front of the hit centre"),
	("OpticZ", "the optic's centre above the floor"),
	("OpticHalfX", "the optic's half-size along the facing"),
	("OpticHalfY", "across"),
	("OpticHalfZ", "up"),
	("NoseX", "the nose on the centre line: the front of the foremost part that crosses it"),
	("NoseZ0", "that part's bottom"),
	("NoseZ1", "and top"),
	("TailX", "the tail on the centre line: the rear of the rearmost part that crosses it, behind the hit centre"),
	("TailZ0", "that part's bottom"),
	("TailZ1", "and top"),
	("TailHalf", "that part's half-width at its rear end"),
	("RearHalf", "the half-width of the rear face (the hull's points at its rearmost)"),
	("RearZ0", "the rear face's bottom"),
	("RearZ1", "and top"),
	("SideY", "a side plate's inner face across the centre line"),
	("SideX0", "the plate's rear end along the facing"),
	("SideX1", "its front end"),
	("SideZ0", "its bottom"),
	("SideZ1", "its top"),
)


_CONSTANTS = []


def constant(key):
	if not _CONSTANTS:
		_CONSTANTS.append(dtconst.load())
	return _CONSTANTS[0][key]["value"]


def load_role(role):
	"""(hull, optic) as the game draws them, in units of the hit diameter (enemy_shapes.py)."""
	path = os.path.join(TOOLS, "blender", f"enemy_{role.lower()}.py")
	spec = importlib.util.spec_from_file_location(f"elite_anchors_{role.lower()}", path)
	module = importlib.util.module_from_spec(spec)
	spec.loader.exec_module(module)
	return es.unreal_parts(module.hull()), es.unreal_parts(module.optic())


def bounds(parts):
	verts = [v for part in parts for v in part["verts"]]
	return [min(v[a] for v in verts) for a in range(3)], [max(v[a] for v in verts) for a in range(3)]


def anchors(role):
	"""{field: value in drawn radii} for one role, from its generator. One unit of the hull is two drawn radii."""
	hull, optic = load_role(role)
	k = 2.0  # hit diameters to radii
	lo, hi = bounds(hull)
	olo, ohi = bounds(optic)
	verts = [v for part in hull for v in part["verts"]]
	out = {
		"Front": hi[0], "Rear": -lo[0], "HalfWidth": max(abs(v[1]) for v in verts), "Bottom": lo[2], "Top": hi[2],
		"Reach": max(math.hypot(v[0], v[1]) for v in verts),
		"OpticX": 0.5 * (olo[0] + ohi[0]), "OpticZ": 0.5 * (olo[2] + ohi[2]),
		"OpticHalfX": 0.5 * (ohi[0] - olo[0]), "OpticHalfY": 0.5 * (ohi[1] - olo[1]), "OpticHalfZ": 0.5 * (ohi[2] - olo[2]),
	}
	crossing = [bounds([part]) for part in hull if bounds([part])[0][1] <= 0.0 <= bounds([part])[1][1]]
	nose = max(crossing, key=lambda b: b[1][0])
	tail = min(crossing, key=lambda b: b[0][0])
	out.update({"NoseX": nose[1][0], "NoseZ0": nose[0][2], "NoseZ1": nose[1][2], "TailX": -tail[0][0], "TailZ0": tail[0][2], "TailZ1": tail[1][2]})
	tail_part = hull[[bounds([part]) for part in hull].index(tail)]
	out["TailHalf"] = max(abs(v[1]) for v in tail_part["verts"] if v[0] <= tail[0][0] + FACE_EPS)
	rear = [v for v in verts if v[0] <= lo[0] + FACE_EPS]
	out.update({"RearHalf": max(abs(v[1]) for v in rear), "RearZ0": min(v[2] for v in rear), "RearZ1": max(v[2] for v in rear)})
	out.update(side_plate(hull, k))
	return {key: round(value * k, 6) for key, value in out.items() if key not in ("SideY", "SideX0", "SideX1", "SideZ0", "SideZ1")} | {
		key: round(value, 6) for key, value in out.items() if key in ("SideY", "SideX0", "SideX1", "SideZ0", "SideZ1")}


def flat_side(part):
	"""(half-width, x0, x1) of a part's flat outer side: the stretch along the facing where it stands at its greatest half-width; None
	when that stretch is under SIDE_FLAT_RATIO of the part's own length (a corner or a swept edge, nothing a plate can lie along)."""
	(x_lo, _, _), (x_hi, y_hi, _) = bounds([part])
	edge = [v[0] for v in part["verts"] if abs(v[1] - y_hi) <= FACE_EPS]
	if not edge or max(edge) - min(edge) < SIDE_FLAT_RATIO * (x_hi - x_lo) - FACE_EPS:
		return None
	return y_hi, min(edge), max(edge)


def side_plate(hull, k):
	"""Where an Armored plate rests, in drawn radii: along the flat outer side of the widest part that runs along the hull (at least
	SIDE_LONG_RATIO of its length), as long as that side, cut where another part stands in the plate's way, no taller than one radius."""
	lo, hi = bounds(hull)
	length = hi[0] - lo[0]
	part_ratio = constant("ELITE.PART_RATIO")
	boxes = [bounds([part]) for part in hull]
	runs = [(index, flat_side(part)) for index, part in enumerate(hull) if boxes[index][1][0] - boxes[index][0][0] >= SIDE_LONG_RATIO * length]
	index, (side, x0, x1) = max(((i, f) for i, f in runs if f), key=lambda item: item[1][0])
	rest = boxes[index]
	side_y = side * k
	z0 = rest[0][2] * k
	z1 = min(rest[1][2] * k, z0 + 1.0)
	y0, y1 = side_y, side_y + part_ratio
	segments = [(x0 * k, x1 * k)]
	for b in boxes:
		if b is rest:
			continue
		bx0, bx1 = b[0][0] * k, b[1][0] * k
		if b[1][1] * k <= y0 + FACE_EPS or b[0][1] * k >= y1 or b[1][2] * k <= z0 or b[0][2] * k >= z1:
			continue
		cut = []
		for s0, s1 in segments:
			if bx1 <= s0 or bx0 >= s1:
				cut.append((s0, s1))
				continue
			if bx0 > s0:
				cut.append((s0, bx0))
			if bx1 < s1:
				cut.append((bx1, s1))
		segments = cut
	x0, x1 = max(segments, key=lambda s: s[1] - s[0])
	return {"SideY": side_y, "SideX0": x0, "SideX1": x1, "SideZ0": z0, "SideZ1": z1}


_TABLE = {}


def table():
	if not _TABLE:
		_TABLE.update({role: anchors(role) for role in ROLES})
	return dict(_TABLE)


def render():
	rows = table()
	lines = [HEADER, "// One row per role with a mesh, in EDTEnemyRole order; every length in drawn radii (hit radius x C.ELITE.DRAW_SCALE), in the hull's", "// frame: +X the facing, +Z up from the floor. DTElite::BuildParts places the elite parts from them (elites.md R-ELT-10, R-ELT-11).", "#pragma once", "", "struct FDTEliteAnchors", "{"]
	for name, what in FIELDS:
		lines.append(f"\tfloat {name}; // {what}")
	lines += ["};", "", "namespace DTEliteAnchorsGen", "{", f"\tinline constexpr int NumRoles = {len(ROLES)};", "\tinline constexpr FDTEliteAnchors Rows[NumRoles] = {"]
	for role in ROLES:
		values = ", ".join(f"{rows[role][name]:.6f}f" for name, _ in FIELDS)
		lines.append(f"\t\t{{ {values} }}, // {role}")
	lines += ["\t};", "}", ""]
	return "\r\n".join(lines)  # .h is eol=crlf (.gitattributes), so the committed bytes are what a checkout holds


# --- placement (the mirror of DTElite::BuildParts) ----------------------------------------------------------------------------

def light_area_ratio(row):
	"""The light's top-view area, the optic's bounds LightCover over, against the hull's top-view bounding area, before the cap."""
	cover = LAYOUT["LightCover"]
	return (2.0 * cover * row["OpticHalfX"]) * (2.0 * cover * row["OpticHalfY"]) / ((row["Front"] + row["Rear"]) * 2.0 * row["HalfWidth"])


def light_half(row):
	"""The light's half-sizes in drawn radii: the optic's bounds LightCover over, scaled down about its centre, keeping its proportions,
	until its top-view area is at most C.EAR.ELITE_LIGHT_AREA_MAX_RATIO of the hull's top-view bounding area (R-EAR-08)."""
	cover = LAYOUT["LightCover"]
	shrink = min(1.0, math.sqrt(constant("EAR.ELITE_LIGHT_AREA_MAX_RATIO") / light_area_ratio(row)))
	return tuple(cover * shrink * row[key] for key in ("OpticHalfX", "OpticHalfY", "OpticHalfZ"))


def place(row, radius, affixes, shield_deg=0.0):
	"""The parts of one elite of drawn radius `radius` (uu) by the anchors `row`, in the hull's frame in uu, z from the floor:
	[(affix or "Light", (cx, cy, cz), (hx, hy, hz), yaw_deg)]. `affixes` is a set of AFFIXES names; shield_deg the orbit's angle."""
	R, L = radius, LAYOUT
	P = R * constant("ELITE.PART_RATIO")
	out = []
	out.append(("Light", (row["OpticX"] * R, 0.0, row["OpticZ"] * R), tuple(h * R for h in light_half(row)), 0.0))

	def rest_z(z0, z1, half):
		# A part against a face sits at the face's middle height, and never below the floor the face stands on.
		return max(z0 * R + half, 0.5 * (z0 + z1) * R)

	if "Armored" in affixes:
		hx, hz = 0.5 * (row["SideX1"] - row["SideX0"]) * R, 0.5 * (row["SideZ1"] - row["SideZ0"]) * R
		for side in (-1.0, 1.0):
			out.append(("Armored", (0.5 * (row["SideX0"] + row["SideX1"]) * R, side * (row["SideY"] * R + 0.5 * P), 0.5 * (row["SideZ0"] + row["SideZ1"]) * R), (hx, 0.5 * P, hz), 0.0))
	if "Swift" in affixes:
		half = (0.5 * L["VaneLength"] * P, 0.5 * L["ThinPart"] * P, 0.5 * L["ThinPart"] * P)
		yaw = math.radians(L["VaneYawDeg"])
		for side in (-1.0, 1.0):
			# The vane's front end at the rear face's corner, the vane trailing back along its own line.
			x = -row["Rear"] * R - half[0] * math.cos(yaw)
			y = side * (row["RearHalf"] * R - half[0] * math.sin(yaw))
			out.append(("Swift", (x, y, rest_z(row["RearZ0"], row["RearZ1"], half[2])), half, side * L["VaneYawDeg"]))
	if "Volatile" in affixes:
		h = 0.5 * L["ReactorSize"] * P
		out.append(("Volatile", (-row["TailX"] * R - h, 0.0, rest_z(row["TailZ0"], row["TailZ1"], h)), (h, h, h), 0.0))
	if "Splitter" in affixes:
		count = int(constant("AFFIX.SPLITTER_COUNT"))
		h = 0.5 * P
		# Across the tail's own rear end, the outer drones flush with its sides; never closer than a drone apart.
		spread = max(row["TailHalf"] * R - h, P) if count > 1 else 0.0
		for dock in range(count):
			y = (-spread + 2.0 * spread * dock / (count - 1)) if count > 1 else 0.0
			out.append(("Splitter", (-row["TailX"] * R - h, y, rest_z(row["TailZ0"], row["TailZ1"], h)), (h, h, h), 0.0))
	if "Vampiric" in affixes:
		half = (0.5 * L["SpikeLength"] * P, 0.5 * L["ThinPart"] * P, 0.5 * L["ThinPart"] * P)
		out.append(("Vampiric", (row["NoseX"] * R + half[0], 0.0, rest_z(row["NoseZ0"], row["NoseZ1"], half[2])), half, 0.0))
	if "Shielded" in affixes:
		plates = int(constant("AFFIX.SHIELD_PLATES"))
		h = 0.5 * P
		orbit = row["Reach"] * R + P + h
		z = rest_z(row["Bottom"], row["Top"], h)
		for plate in range(plates):
			a = math.radians(shield_deg) + 2.0 * math.pi * plate / plates
			out.append(("Shielded", (orbit * math.cos(a), orbit * math.sin(a), z), (h, h, h), math.degrees(a)))
	return out


def cube_place(radius, role, affixes, shield_deg=0.0):
	"""Today's placement from the hit circle (DTElite.cpp before D-076, still the grey box's and the boss's), in the same frame:
	the cube of half-size R centred C.SIM.PLANE_Z_UU above the floor, which the role meshes stand on."""
	R, L = radius, LAYOUT
	P = R * constant("ELITE.PART_RATIO")
	Z = constant("SIM.PLANE_Z_UU")
	optic = constant("ENEMIES.OPTIC_SCALE")
	out = [("Light", (0.0 if role == "Turret" else (1.0 - optic) * R, 0.0, Z + R), (optic * R,) * 3, 0.0)]
	if "Armored" in affixes:
		for side in (-1.0, 1.0):
			out.append(("Armored", (0.0, side * (R + 0.5 * P), Z), (R, 0.5 * P, 0.5 * R), 0.0))
	if "Swift" in affixes:
		for side in (-1.0, 1.0):
			out.append(("Swift", (-R, side * R, Z), (0.5 * L["VaneLength"] * P, 0.5 * L["ThinPart"] * P, 0.5 * L["ThinPart"] * P), side * L["VaneYawDeg"]))
	if "Volatile" in affixes:
		out.append(("Volatile", (-(R + 0.5 * L["ReactorSize"] * P), 0.0, Z), (0.5 * L["ReactorSize"] * P,) * 3, 0.0))
	if "Splitter" in affixes:
		count = int(constant("AFFIX.SPLITTER_COUNT"))
		for dock in range(count):
			out.append(("Splitter", (-(R + P), (dock - 0.5 * (count - 1)) * 2.0 * P, Z), (0.5 * P,) * 3, 0.0))
	if "Vampiric" in affixes:
		out.append(("Vampiric", (R + 0.5 * L["SpikeLength"] * P, 0.0, Z), (0.5 * L["SpikeLength"] * P, 0.5 * L["ThinPart"] * P, 0.5 * L["ThinPart"] * P), 0.0))
	if "Shielded" in affixes:
		plates = int(constant("AFFIX.SHIELD_PLATES"))
		for plate in range(plates):
			a = math.radians(shield_deg) + 2.0 * math.pi * plate / plates
			out.append(("Shielded", ((R + L["ShieldOrbit"] * P) * math.cos(a), (R + L["ShieldOrbit"] * P) * math.sin(a), Z), (0.5 * P,) * 3, math.degrees(a)))
	return out


def box_part(name, centre, half, yaw_deg):
	"""A placed part as an enemy_shapes solid in uu."""
	c, s = math.cos(math.radians(yaw_deg)), math.sin(math.radians(yaw_deg))
	corners = [(-half[0], -half[1]), (half[0], -half[1]), (half[0], half[1]), (-half[0], half[1])]
	outline = [(centre[0] + x * c - y * s, centre[1] + x * s + y * c) for x, y in corners]
	return es.prism(name, outline, centre[2] - half[2], centre[2] + half[2])


def main(argv):
	text = render()
	if "--check" in argv:
		have = None
		if os.path.exists(OUT):
			with open(OUT, encoding="utf-8", newline="") as f:
				have = f.read()
		if have != text:
			print("ELITE ANCHORS: FAIL (DTEliteAnchorsGen.h is hand-edited or out of date with the generators; run python -I Tools/elite_anchors.py)")
			return 1
		print(f"ELITE ANCHORS: PASS ({len(ROLES)} roles)")
		return 0
	with open(OUT, "w", encoding="utf-8", newline="") as f:
		f.write(text)
	print(f"wrote {os.path.relpath(OUT, ROOT)}")
	return 0


if __name__ == "__main__":
	sys.exit(main(sys.argv[1:]))
